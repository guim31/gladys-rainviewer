export const GLYPH_WIDTH = 6; // 5 columns and one of spacing
export const GLYPH_HEIGHT = 7;

/**
 * Width of a text in pixels.
 * @param {string} text - The text (unknown characters are skipped).
 * @returns {number} Pixels.
 */
export function textWidth(text) {
  return [...text].filter((char) => GLYPHS[char]).length * GLYPH_WIDTH;
}

/**
 * Draw a text into an RGBA bitmap.
 * @param {{ data: Uint8Array, width: number, height: number }} bitmap - Target.
 * @param {string} text - The text.
 * @param {number} left - Pixel.
 * @param {number} top - Pixel.
 * @param {number[]} rgb - Color.
 */
export function drawText(bitmap, text, left, top, rgb) {
  let x = left;
  for (const char of text) {
    const glyph = GLYPHS[char];
    if (!glyph) {
      continue;
    }
    for (let row = 0; row < GLYPH_HEIGHT; row += 1) {
      for (let col = 0; col < 5; col += 1) {
        const px = x + col;
        const py = top + row;
        if (
          glyph[row][col] === '1' &&
          px >= 0 &&
          py >= 0 &&
          px < bitmap.width &&
          py < bitmap.height
        ) {
          const i = (py * bitmap.width + px) * 4;
          bitmap.data[i] = rgb[0];
          bitmap.data[i + 1] = rgb[1];
          bitmap.data[i + 2] = rgb[2];
          bitmap.data[i + 3] = 255;
        }
      }
    }
    x += GLYPH_WIDTH;
  }
}
